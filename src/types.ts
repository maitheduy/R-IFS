export interface Complex {
  x: number; // Real part
  y: number; // Imaginary part
}

export interface MapParams {
  id: number;
  name: string;
  // Affine transformation: z' = r * e^(i * theta) * z + c
  // or more generally: a*z + b*z_bar + c (for complex affines)
  scale: number;        // r (contraction factor, e.g. 0.5)
  rotationDeg: number;  // theta in degrees (e.g. 0, 120, 240)
  tx: number;           // translation real part (e.g. 1)
  ty: number;           // translation imaginary part (e.g. 0)
  color: string;        // Hex color for rendering points generated by this map
  probability: number;  // Relative probability weight in Chaos game
}

export interface IFSConfig {
  name: string;
  description: string;
  rotationAngleDeg: number; // Base rotation angle (e.g. 120 for 2pi/3)
  numMaps: number;          // Number of symmetric branches N (e.g. 3)
  maps: MapParams[];
  baseContraction: {
    scale: number;
    tx: number;
    ty: number;
  };
}

export type ColorMode = 'map' | 'density' | 'rainbow' | 'monochrome';

export interface SimulatorState {
  pointsPerFrame: number;
  totalPoints: number;
  isRunning: boolean;
  colorMode: ColorMode;
  pointSize: number;
  opacity: number;
  speedMultiplier: number;
  zoom: number;
  panX: number;
  panY: number;
}

export interface ProofStep {
  stepNumber: number;
  titleVi: string;
  titleEn: string;
  contentVi: string;
  contentEn: string;
  formula: string;
}
